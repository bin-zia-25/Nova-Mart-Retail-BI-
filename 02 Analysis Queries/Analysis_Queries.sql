-- Give me the top 3 products by revenue inside every category.
Select 
	CategoryName,
	ProductName,
	Revenue
From
(
Select 
	CategoryName,
	ProductName,
	Revenue,
	Row_Number() over (Partition by CategoryName order by Revenue DESC) as Rank
From 
	Categories C Inner Join 
(
Select
	P.CategoryID,
	P.ProductID,
	P.ProductName,
	Sum((OD.UnitPrice*OD.Quantity)*(1-(OD.Discount/100))) as Revenue
From 
	Products P Inner join OrderDetails OD on P.ProductID = OD.ProductID
Group by 
	P.categoryID,
	P.Productname,
	P.ProductID
) as T 	
on T.CategoryID = C.CategoryID
) as F
Where 
	Rank <= 3

