-- For each month, show the current month's revenue and the next month's revenue
Select
	Format(Month_Year,'MMMM yyyy') as Month_Year,
	Revenue,
	Lag(Revenue) over (order by Month_Year) as Previous_Month_Revenue,
	Lead(Revenue) over (order by Month_Year) as Next_Month_Revenue,
	(Revenue - Lag(Revenue) over (Order by Month_Year) ) as Difference
From
(
Select
	Month_Year,
	Sum((OD.Quantity*OD.UnitPrice)*(1-OD.Discount/100)) as Revenue
From OrderDetails OD inner join 
(
Select
	OrderID,
	DateFromParts(Year(OrderDate),
				  Month(OrderDate),
				  1) as Month_Year
From 
	Orders 
	) as T
on T.OrderID = OD.OrderID
Group by 
	Month_Year
) as F

